// Generates (and re-generates) a block at the end of src/styles.css that lifts every text colour rule that
// fails WCAG AA (4.5:1) in the light or dark theme, keeping hue/chroma. Run: node scripts/a11y-contrast.mjs
import postcss from "postcss";
import fs from "node:fs";
const FILE = new URL("../src/styles.css", import.meta.url).pathname;
const START = "/* a11y-contrast:start (generated by scripts/a11y-contrast.mjs) */";
const END = "/* a11y-contrast:end */";
let css = fs.readFileSync(FILE, "utf8");
// replace ONLY the generated block (rules written after it must survive)
const i0 = css.indexOf(START);
const i1 = css.indexOf(END);
if (i0 >= 0 && i1 > i0)
  css = (css.slice(0, i0).trimEnd() + "\n" + css.slice(i1 + END.length)).trimEnd() + "\n";
else if (i0 >= 0)
  throw new Error("a11y-contrast: start marker without end marker — refusing to edit styles.css");

const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const toOk = ([r, g, b]) => {
  const [R, G, B] = [r, g, b].map(lin);
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B),
    m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B),
    s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  };
};
const fromOk = ({ L, a, b }) => {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3,
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3,
    s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map((c) => Math.max(0, Math.min(1, gam(Math.max(0, Math.min(1, c))))));
};
const hex = (rgb) =>
  "#" +
  rgb
    .map((c) =>
      Math.round(c * 255)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("");
const lum = ([r, g, b]) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
function parse(v) {
  v = v.trim();
  let m;
  if ((m = /^#([0-9a-f]{6})$/i.exec(v)))
    return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16) / 255);
  if ((m = /^#([0-9a-f]{3})$/i.exec(v))) return [...m[1]].map((c) => parseInt(c + c, 16) / 255);
  if ((m = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)$/.exec(v))) {
    const h = (+m[3] * Math.PI) / 180;
    return fromOk({ L: +m[1], a: +m[2] * Math.cos(h), b: +m[2] * Math.sin(h) });
  }
  if ((m = /^rgb\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)$/.exec(v)))
    return [+m[1] / 255, +m[2] / 255, +m[3] / 255];
  return null;
}
const root = postcss.parse(css);
const maps = { light: {}, dark: {} };
root.walkRules((r) => {
  if (/^:root$/.test(r.selector))
    r.walkDecls((d) => {
      if (d.prop.startsWith("--")) maps.light[d.prop] = d.value;
    });
  if (r.selector === ".dark")
    r.walkDecls((d) => {
      if (d.prop.startsWith("--")) maps.dark[d.prop] = d.value;
    });
});
const resolve = (v, theme, depth = 0) => {
  v = v.trim();
  const m = /^var\((--[\w-]+)(?:,[^)]*)?\)$/.exec(v);
  if (!m) return parse(v);
  if (depth > 8) return null;
  const x = theme === "dark" ? (maps.dark[m[1]] ?? maps.light[m[1]]) : maps.light[m[1]];
  return x ? resolve(x, theme, depth + 1) : null;
};
const DARK_CTX =
  /(main-sidebar|\.sidebar|\.brand|room-card|classroom-hero|\.scene|speaker-card|hero-|\.board|chalk|journey-dark)/;
const LIGHT_CTX = /(sidebar-note|desk-note|quote-note|\.hero-cta|practice-card\.yellow)/;
const YELLOW = parse("#f0c551");
const REF = {
  light: { light: parse("#e9e0cf"), dark: parse("#1e553b") },
  dark: { light: parse("#2b4034"), dark: parse("#1e553b") },
};
const TARGET = 4.6;
function lift(rgb, ref, wantLighter) {
  if (ratio(rgb, ref) >= TARGET) return null;
  const ok = toOk(rgb);
  for (let k = 1; k <= 90; k++) {
    const L = ok.L + (wantLighter ? 1 : -1) * k * 0.01;
    if (L < 0 || L > 1) break;
    const sc = L / Math.max(ok.L, 0.01);
    const c = fromOk({ L, a: ok.a * (wantLighter ? 1 : 1), b: ok.b });
    if (ratio(c, ref) >= TARGET) return c;
    void sc;
  }
  return wantLighter ? [1, 1, 1] : [0, 0, 0];
}
const out = [];
const rootVars = [];
const darkVars = [];
let n = 0;
const seen = new Set();
root.walkRules((rule) => {
  if (/^(:root|\.dark)$/.test(rule.selector)) return;
  let at = rule.parent;
  if (at?.type === "atrule" && !/^media$/.test(at.name)) return; // keyframes etc.
  rule.walkDecls("color", (d) => {
    if (/^(inherit|currentColor|transparent|unset|initial)$/i.test(d.value.trim())) return;
    const ctx = LIGHT_CTX.test(rule.selector)
      ? "light"
      : DARK_CTX.test(rule.selector)
        ? "dark"
        : "light";
    // the rule's own solid background, when it has one, is the real reference
    let own = null;
    rule.walkDecls(/^background(-color)?$/, (b) => {
      if (!/gradient|url|color-mix|rgba/i.test(b.value))
        own = { l: resolve(b.value, "light"), d: resolve(b.value, "dark") };
    });
    const mixM =
      /^color-mix\(in (?:oklab|srgb),\s*(var\([^)]+\)|#[0-9a-f]{3,6})\s+(\d+)%,\s*transparent\)$/i.exec(
        d.value.trim(),
      );
    const base = mixM ? mixM[1] : d.value;
    if (/color-mix|rgba|hsla/i.test(base)) return;
    const fgL = resolve(base, "light");
    const fgD = resolve(base, "dark");
    if (!fgL || !fgD) return;
    const refL =
      own?.l ?? (ctx === "light" && LIGHT_CTX.test(rule.selector) ? YELLOW : REF.light[ctx]);
    const refD = own?.d ?? REF.dark[ctx];
    const wantLighterL = own?.l ? lum(own.l) < 0.4 : ctx === "dark";
    const wantLighterD = own?.d ? lum(own.d) < 0.4 : true;
    const eff = (fg, ref) =>
      mixM ? fg.map((c, i) => c * (+mixM[2] / 100) + ref[i] * (1 - +mixM[2] / 100)) : fg;
    const adjL =
      ratio(eff(fgL, refL), refL) >= TARGET ? null : (lift(fgL, refL, wantLighterL) ?? fgL);
    // paper notes stay yellow in dark mode, so they keep their dark text there too
    const paper = LIGHT_CTX.test(rule.selector) && !own;
    const adjD = paper
      ? (adjL ?? fgL)
      : ratio(eff(fgD, refD), refD) >= TARGET
        ? null
        : (lift(fgD, refD, wantLighterD) ?? fgD);
    if (!adjL && !adjD) return;
    const key = `${rule.selector}|${at?.type === "atrule" ? at.params : ""}|${d.value}`;
    if (seen.has(key)) return;
    seen.add(key);
    const name = `--a11y-${++n}`;
    rootVars.push(`  ${name}: ${hex(adjL ?? fgL)};`);
    darkVars.push(`  ${name}: ${hex(adjD ?? fgD)};`);
    const decl = `${rule.selector}{color:var(${name})}`;
    out.push(at?.type === "atrule" ? `@media ${at.params}{${decl}}` : decl);
  });
});
// global muted text token used by utility classes
const mf = {
  light: resolve("var(--muted-foreground)", "light"),
  dark: resolve("var(--muted-foreground)", "dark"),
};
const mL = lift(mf.light, REF.light.light, false),
  mD = lift(mf.dark, REF.dark.light, true);
const block = [
  START,
  `:root{${mL ? `\n  --muted-foreground: ${hex(mL)};` : ""}\n${rootVars.join("\n")}\n}`,
  `.dark{${mD ? `\n  --muted-foreground: ${hex(mD)};` : ""}\n${darkVars.join("\n")}\n}`,
  ...out,
  END,
].join("\n");
fs.writeFileSync(FILE, css.trimEnd() + "\n\n" + block + "\n");
console.log(
  `adjusted ${n} text-colour rules; muted-foreground ${mL ? "darkened" : "ok"} (light), ${mD ? "lightened" : "ok"} (dark)`,
);
